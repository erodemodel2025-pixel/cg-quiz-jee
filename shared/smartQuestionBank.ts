type CompactQ = [
  id: string,
  category: Exclude<GameCategoryId, 'all'>,
  topic: string,
  question: string,
  options: [string, string, string, string],
  correctIndex: 0 | 1 | 2 | 3,
  explanation: string,
];

function buildTier(
  difficulty: GameDifficultyId,
  marks: 10 | 20 | 30 | 50,
  items: CompactQ[]
): SmartGameQuestion[] {
  return items.map(([id, category, topic, question, options, correctIndex, explanation]) => ({
    id,
    difficulty,
    category,
    topic,
    question,
    options,
    correctIndex,
    explanation,
    marks,
  }));
}

