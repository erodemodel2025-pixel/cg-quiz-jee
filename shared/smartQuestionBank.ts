export const SMART_QUESTION_BANK: SmartGameQuestion[] = [
  ...buildTier('easy', 10, EASY_BANK),
  ...buildTier('moderate', 20, MODERATE_BANK),
  ...buildTier('hard', 30, HARD_BANK),
  ...buildTier('jee', 50, JEE_BANK),
];

export const SMART_QUESTION_MAP = new Map(SMART_QUESTION_BANK.map((q) => [q.id, q]));

function shuffleArray<T>(items: readonly T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function shuffleSmartQuestionOptions(q: SmartGameQuestion): SmartGameQuestion {
  const perm = shuffleArray([0, 1, 2, 3]);
  const options = perm.map((idx) => q.options[idx]) as [string, string, string, string];
  const correctIndex = perm.indexOf(q.correctIndex) as 0 | 1 | 2 | 3;
  return { ...q, options, correctIndex };
}

/**
 * Strictly selects `count` unique questions at the requested `difficulty` level.
 * If a specific category has fewer questions at that difficulty than `count`,
 * fills remaining slots ONLY from the SAME exact difficulty level (never leaks wrong difficulty!).
 */
export function selectSmartGameQuestions(params: {
  difficulty: GameDifficultyId;
  category?: string;
  count?: number;
}): SmartGameQuestion[] {
  const targetCount = Math.max(5, Math.min(25, Math.round(params.count ?? 10)));
  const category = (params.category || 'all').trim();

  const tierPool = SMART_QUESTION_BANK.filter((q) => q.difficulty === params.difficulty);
  const categoryMatches =
    category === 'all'
      ? tierPool
      : tierPool.filter((q) => q.category === category);

  const picked: SmartGameQuestion[] = [];
  const usedIds = new Set<string>();

  for (const q of shuffleArray(categoryMatches)) {
    if (picked.length >= targetCount) break;
    if (!usedIds.has(q.id)) {
      usedIds.add(q.id);
      picked.push(q);
    }
  }

  if (picked.length < targetCount) {
    const fallbackSameTier = shuffleArray(tierPool.filter((q) => !usedIds.has(q.id)));
    for (const q of fallbackSameTier) {
      if (picked.length >= targetCount) break;
      usedIds.add(q.id);
      picked.push(q);
    }
  }

  return picked.map(shuffleSmartQuestionOptions);
}
